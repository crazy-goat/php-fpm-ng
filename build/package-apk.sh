#!/bin/sh
# Build the php-fpm-ng .apk: the binary from build/libphp-build.sh, a
# configuration a user can start from, and an OpenRC service (issue #222).
#
# The Alpine twin of build/package-deb.sh, and the same bargain: the package
# contains no PHP and depends on php85-embed for the libphp it was linked
# against, so `apk add php85-embed && apk add --allow-untrusted ./php-fpm-ng-*.apk`
# is the whole installation.
#
# Two things differ from the Debian side and both come from Alpine:
#
#   - libphp lives in /usr/lib/php85/, which is not on the default library
#     path. build/libphp-build.sh already writes an RPATH pointing there, which
#     is why the binary resolves it at all -- and it pins the minor harder than
#     the Debian package can, because the path names the version.
#   - The apk is unsigned unless a key is supplied. `apk add` then wants
#     --allow-untrusted. Signing is issue #223's decision, not this script's;
#     if ABUILD_PRIVKEY is set, abuild signs with it.
#
# Usage: build/package-apk.sh <binary> [outdir]
#   binary   php-fpm-ng from build/libphp-build.sh
#   outdir   where the .apk lands, default ./out-apk
set -eu

fail() { echo "package-apk.sh: FAIL: $*" >&2; exit 1; }

REPO=$(cd "$(dirname "$0")/.." && pwd)
BIN=${1:?usage: build/package-apk.sh <binary> [outdir]}
OUT=${2:-$PWD/out-apk}
[ -x "$BIN" ] || fail "$BIN is not an executable"

command -v abuild >/dev/null || fail "abuild is not installed (apk add alpine-sdk)"

# See the same paragraph in build/package-deb.sh: the version is asked of the
# binary, not of the build host, so a host with two PHPs cannot produce a
# package whose dependency names a version its own binary was not linked
# against.
PHP_FULL=$("$BIN" -n -v 2>/dev/null | sed -n 's/^PHP \([0-9.]*\).*/\1/p' | head -1)
[ -n "$PHP_FULL" ] || fail "$BIN -v printed no version banner. Most often this host is
  missing a library the binary links -- it does not run, so it cannot be asked. Try:
$(ldd "$BIN" 2>&1 | grep -i 'not found\|Error' || echo '  (ldd found everything; run the binary by hand to see why)')"
PHP_PKG=php$(echo "$PHP_FULL" | sed 's/^\([0-9]*\)\.\([0-9]*\).*/\1\2/')

readelf -d "$BIN" 2>/dev/null | grep -q 'libphp\.so' \
    || fail "$BIN does not link libphp.so; this package is only for the build/libphp-build.sh output"

# Which of the two packages this is (issue #294). The reasoning is written out
# in build/package-deb.sh: the name comes off the binary's symbols and not off
# FPMNG_TLS, so that a package cannot call itself something the artefact in it
# is not. nm is in binutils, which alpine-sdk already brings in for abuild.
command -v nm >/dev/null || fail "nm is not installed (apk add binutils)"
has_symbol() { nm --defined-only "$BIN" 2>/dev/null | grep -qw -- "$1"; }

HAS_TLS=0; has_symbol fpm_tls_http_validate && HAS_TLS=1
HAS_ACME=0; has_symbol fpm_acme_challenge_init_main && HAS_ACME=1

case "$HAS_TLS$HAS_ACME" in
00) PKGNAME=php-fpm-ng
    PKGDESC="FPM process manager with HTTP-direct pools, on the distribution PHP; no TLS, no ACME" ;;
11) PKGNAME=php-fpm-ng-tls
    PKGDESC="FPM process manager with HTTP-direct pools and BETA, unaudited TLS termination and ACME issuance" ;;
*)  fail "this binary has TLS=$HAS_TLS ACME=$HAS_ACME, which is neither of the two
  packages this repository publishes (issue #294): the default one is built with
  neither, php-fpm-ng-tls with both (FPMNG_TLS=1 FPMNG_ACME=1)." ;;
esac

# See build/package-deb.sh on FPMNG_RELEASE. apk's pkgver has to stay the PHP
# version and pkgrel an integer, so ours goes into pkgdesc, which `apk info -d`
# prints -- the one field a user reads before installing.
COMMIT=$(cd "$REPO" && git rev-parse --short HEAD 2>/dev/null || echo unknown)
RELEASE=${FPMNG_RELEASE:-$COMMIT}

WORK=$OUT/abuild
rm -rf "$WORK"
mkdir -p "$WORK/src"
cp "$BIN" "$WORK/src/php-fpm-ng"
cp "$REPO/packaging/apk/php-fpm-ng.conf" "$REPO/packaging/apk/www.conf" \
   "$REPO/packaging/apk/php-fpm-ng.initd" "$WORK/src/"

# The two packages own the same files, so each one replaces the other and both
# provide the virtual php-fpm-ng-any (issue #294). replaces= is what lets apk
# hand /usr/sbin/php-fpm-ng over when one is installed over the other; two
# installed packages providing the same name is what apk refuses, which is how
# they stay mutually exclusive. The Debian side says the same thing in
# Conflicts/Replaces/Provides -- see build/package-deb.sh.
[ "$PKGNAME" = php-fpm-ng-tls ] && OTHER=php-fpm-ng || OTHER=php-fpm-ng-tls

cat > "$WORK/APKBUILD" <<EOT
# Generated by build/package-apk.sh -- edit that, not this.
pkgname=$PKGNAME
pkgver=$PHP_FULL
pkgrel=1
pkgdesc="$PKGDESC ($RELEASE)"
url="https://github.com/crazy-goat/php-fpm-ng"
arch="$(abuild -A 2>/dev/null || echo x86_64)"
license="PHP-3.01"
depends="$PHP_PKG-embed"
provides="php-fpm-ng-any"
replaces="$OTHER"
options="!check !strip"
source=""
subpackages=""

package() {
	install -Dm0755 "\$srcdir"/php-fpm-ng "\$pkgdir"/usr/sbin/php-fpm-ng
	install -Dm0644 "\$srcdir"/php-fpm-ng.conf "\$pkgdir"/etc/php-fpm-ng/php-fpm-ng.conf
	install -Dm0644 "\$srcdir"/www.conf "\$pkgdir"/etc/php-fpm-ng/conf.d/www.conf
	install -Dm0755 "\$srcdir"/php-fpm-ng.initd "\$pkgdir"/etc/init.d/php-fpm-ng
	install -dm0750 "\$pkgdir"/var/log/php-fpm-ng
}
EOT

# abuild's dependency scan is left ON: it turns the NEEDED entries into so:
# dependencies, which is how libevent and libacl get pulled in on the user's
# machine. It produces so:libphp.so as well, and that one is satisfied by any
# php*-embed -- the SONAME does not name a minor. The explicit depends= above
# is what pins it, exactly as Depends: libphp8.5-embed does on the Debian side.
#
# !strip: the binary is the one build/libphp-build.sh produced and verified.
# abuild stripping it afterwards would mean the artefact that ships is not the
# artefact that was tested.

( cd "$WORK" && REPODEST="$OUT/repo" abuild -F -P "$OUT/repo" rootpkg ) >/dev/null

APK=$(find "$OUT/repo" -name "$PKGNAME-[0-9]*.apk" | head -1)
[ -n "$APK" ] || fail "abuild produced no $PKGNAME .apk under $OUT/repo"

echo "package-apk.sh: PASS ($APK, depends on $PHP_PKG-embed)"
