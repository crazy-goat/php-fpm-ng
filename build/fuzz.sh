#!/bin/sh
# Build the libFuzzer harnesses in tests/fuzz/ and run each one (issue #995).
#
#   build/fuzz.sh [-t seconds] [-o outdir] [-r] [-q] [harness ...]
#
#   -t seconds  time for each harness (default 10; 0 = build only)
#   -o outdir   build, corpus and crash output (default $REPO/out-fuzz, or
#               $FUZZ_OUT); keep it out of git
#   -r          run only: skip the build, use the binaries already in outdir
#   -q          quiet, for CI: the harness output goes to outdir/logs/<name>.log
#               and is not printed. A failed run prints only its name, its exit
#               code and the local reproduce command.
#   harness     names without the fuzz_ prefix, for example http_client
#               (default: every tests/fuzz/fuzz_*.c)
#
# Needs clang with the libFuzzer runtime (libclang-rt-dev on Ubuntu), the
# php8.5-dev and libphp8.5-embed packages, and libevent-dev. The compile
# flags match build/libphp-build.sh; the SUPPLIED list below is a copy of that
# script's list, so change both together.
#
# Each harness runs as ./fuzz_<name> <corpus> <seeds>: new inputs go to the
# corpus directory in outdir, and the seeds in tests/fuzz/seeds/<name> are only
# read. A crash writes its reproducer under outdir/artifacts/<name>/.
set -eu

REPO=$(cd "$(dirname "$0")/.." && pwd)
SECONDS_PER_HARNESS=10
OUT=${FUZZ_OUT:-$REPO/out-fuzz}
BUILD=1
QUIET=0

while getopts "t:o:rq" opt; do
	case "$opt" in
	t) SECONDS_PER_HARNESS=$OPTARG ;;
	o) OUT=$OPTARG ;;
	r) BUILD=0 ;;
	q) QUIET=1 ;;
	*) echo "usage: build/fuzz.sh [-t seconds] [-o outdir] [-r] [-q] [harness ...]" >&2; exit 2 ;;
	esac
done
shift $((OPTIND - 1))

fail() {
	echo "fuzz.sh: $*" >&2
	exit 1
}

NAMES=
if [ "$#" -gt 0 ]; then
	NAMES=$*
else
	for src in "$REPO"/tests/fuzz/fuzz_*.c; do
		base=${src##*/fuzz_}
		NAMES="$NAMES ${base%.c}"
	done
fi

# --- php-config and libphp, as build/libphp-build.sh finds them ---------------
PHP_CONFIG=${PHP_CONFIG:-}
if [ -z "$PHP_CONFIG" ]; then
	for c in php-config8.5 php-config85 php-config; do
		if command -v "$c" >/dev/null 2>&1; then
			PHP_CONFIG=$c
			break
		fi
	done
fi
[ -n "$PHP_CONFIG" ] || fail "no php-config found; install php8.5-dev"
CORE_INC=$("$PHP_CONFIG" --includes)
LIBPHP_DIR='' LIBPHP_NAME=''
for dir in "$(dirname "$("$PHP_CONFIG" --extension-dir)")" "$("$PHP_CONFIG" --prefix)/lib" /usr/lib /usr/lib64; do
	for name in php8.5 php; do
		if [ -e "$dir/lib$name.so" ]; then
			LIBPHP_DIR=$dir
			LIBPHP_NAME=$name
			break 2
		fi
	done
done
[ -n "$LIBPHP_NAME" ] || fail "no libphp shared object; install libphp8.5-embed"

CC=${CC:-clang}
SAN="-fsanitize=fuzzer,address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer"
CFLAGS="-D_GNU_SOURCE -O1 -g -fno-strict-aliasing -Wno-deprecated-declarations $SAN"
# Same as SUPPLIED in build/libphp-build.sh, with the optional TLS, ACME and
# fault-injection switches left off: the harnesses do not need them. The quotes
# in PROC_MEM_FILE stay in the word list, so the C macro is a string literal.
# shellcheck disable=SC2089
DEFS="-DHAVE_CONFIG_H -DHAVE_EPOLL=1 -DHAVE_SELECT=1 -DHAVE_BUILTIN_ATOMIC=1
	-DHAVE_LQ_TCP_INFO=1 -DHAVE_TIMES=1 -DHAVE_CLEARENV=1 -DHAVE_CLOCK_GETTIME=1
	-DHAVE_FPM_HTTP=1 -DFPMNG_LIBPHP_BUILD=1 -DFPMNG_SERVE_WRAP=1 -DPROC_MEM_FILE=\"mem\""

TREE=$OUT/tree
if [ "$BUILD" = 1 ]; then
	mkdir -p "$OUT/bin" "$OUT/compat" "$OUT/obj"
	sh "$REPO/build/standalone-tree.sh" "$TREE"
	cat > "$OUT/compat/config.h" <<'SHIM'
/* Generated by build/fuzz.sh: the same shim build/libphp-build.sh writes. */
#include "php_config.h"
SHIM
	INC="-I$TREE/main $CORE_INC -I$TREE/sapi/fpmng -I$TREE/sapi/fpmng/fpm -I$REPO/ext/fpmng_metrics -I$REPO/build/libphp -I$OUT/compat"
	# $DEFS and $INC are word lists, split on purpose; see DEFS above.
# shellcheck disable=SC2086,SC2090
	$CC $CFLAGS $DEFS $INC -c "$REPO/tests/fuzz/stubs.c" -o "$OUT/obj/stubs.o"
fi

status=0
for name in $NAMES; do
	src=$REPO/tests/fuzz/fuzz_$name.c
	bin=$OUT/bin/fuzz_$name
	[ -f "$src" ] || fail "no harness $src"
	if [ "$BUILD" = 1 ]; then
		echo "fuzz.sh: building fuzz_$name"
		# $DEFS and $INC are word lists, split on purpose; see DEFS above.
		# shellcheck disable=SC2086,SC2090
		$CC $CFLAGS $DEFS $INC -o "$bin" "$src" "$OUT/obj/stubs.o" \
			-L"$LIBPHP_DIR" -Wl,-rpath,"$LIBPHP_DIR" -l"$LIBPHP_NAME" -levent -lm
	fi
	[ "$SECONDS_PER_HARNESS" -gt 0 ] || continue
	[ -x "$bin" ] || fail "no binary $bin; run without -r first"
	corpus=$OUT/corpus/$name
	artifacts=$OUT/artifacts/$name/
	mkdir -p "$corpus" "$artifacts"
	echo "fuzz.sh: running fuzz_$name for ${SECONDS_PER_HARNESS}s"
	if [ "$QUIET" = 1 ]; then
		# The output can hold sanitizer reports and crash inputs. It goes to a
		# file that no CI step uploads; only the verdict is printed.
		mkdir -p "$OUT/logs"
		rc=0
		UBSAN_OPTIONS=print_stacktrace=1 "$bin" "$corpus" "$REPO/tests/fuzz/seeds/$name" \
			-max_total_time="$SECONDS_PER_HARNESS" -print_final_stats=1 -timeout=10 \
			-artifact_prefix="$artifacts" >"$OUT/logs/$name.log" 2>&1 || rc=$?
		if [ "$rc" -ne 0 ]; then
			echo "fuzz_$name exit $rc: crash found, reproduce locally with build/fuzz.sh $name"
			status=1
		fi
	elif ! UBSAN_OPTIONS=print_stacktrace=1 "$bin" "$corpus" "$REPO/tests/fuzz/seeds/$name" \
		-max_total_time="$SECONDS_PER_HARNESS" -print_final_stats=1 -timeout=10 \
		-artifact_prefix="$artifacts"; then
		echo "fuzz.sh: fuzz_$name failed; reproducers in $artifacts" >&2
		status=1
	fi
done
exit "$status"
